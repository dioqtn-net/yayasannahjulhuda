-- 5. TABEL INFORMASI PPDB (ppdb_info)
CREATE TABLE IF NOT EXISTS ppdb_info (
    id INT PRIMARY KEY DEFAULT 1,
    academic_year TEXT NOT NULL DEFAULT '2024/2025',
    status TEXT DEFAULT 'BUKA',
    schedule TEXT,
    requirements TEXT,
    flow TEXT,
    fees TEXT,
    wa_number TEXT,
    greeting_title TEXT,
    greeting_desc TEXT,
    contact_person JSONB,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE ppdb_info ADD COLUMN IF NOT EXISTS greeting_title TEXT;
ALTER TABLE ppdb_info ADD COLUMN IF NOT EXISTS greeting_desc TEXT;
ALTER TABLE ppdb_info ADD COLUMN IF NOT EXISTS contact_person JSONB;

-- 6. TABEL JENJANG PENDIDIKAN / PROGRAM (education_units)
CREATE TABLE IF NOT EXISTS education_units (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    accreditation TEXT,
    description TEXT,
    curriculum TEXT,
    vision TEXT,
    mission TEXT,
    featured_programs TEXT,
    extracurricular TEXT,
    facilities TEXT,
    image_url TEXT,
    wa_number TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE education_units ADD COLUMN IF NOT EXISTS accreditation TEXT;
ALTER TABLE education_units ADD COLUMN IF NOT EXISTS vision TEXT;
ALTER TABLE education_units ADD COLUMN IF NOT EXISTS mission TEXT;
ALTER TABLE education_units ADD COLUMN IF NOT EXISTS featured_programs TEXT;

-- 7. TABEL FASILITAS (facilities)
CREATE TABLE IF NOT EXISTS facilities (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    description TEXT,
    image_url TEXT,
    images JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE facilities ADD COLUMN IF NOT EXISTS images JSONB;

-- 8. TABEL BERITA (news_posts)
CREATE TABLE IF NOT EXISTS news_posts (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    content TEXT,
    date DATE DEFAULT CURRENT_DATE,
    jenjang TEXT DEFAULT 'Semua',
    summary TEXT,
    image_url TEXT,
    images JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE news_posts ADD COLUMN IF NOT EXISTS jenjang TEXT DEFAULT 'Semua';
ALTER TABLE news_posts ADD COLUMN IF NOT EXISTS summary TEXT;
ALTER TABLE news_posts ADD COLUMN IF NOT EXISTS images JSONB;

-- 9. TABEL GALERI (galleries)
CREATE TABLE IF NOT EXISTS galleries (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'kegiatan',
    jenjang TEXT DEFAULT 'Semua',
    description TEXT,
    event_date DATE,
    image_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE galleries ADD COLUMN IF NOT EXISTS category TEXT DEFAULT 'kegiatan';
ALTER TABLE galleries ADD COLUMN IF NOT EXISTS jenjang TEXT DEFAULT 'Semua';
ALTER TABLE galleries ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE galleries ADD COLUMN IF NOT EXISTS event_date DATE;


