CREATE POLICY "Auth Delete" ON storage.objects FOR DELETE USING (bucket_id = 'media' AND auth.role() = 'authenticated');


-- 2. TABLES
CREATE TABLE IF NOT EXISTS profile_settings (
    id INT PRIMARY KEY DEFAULT 1,
    name TEXT NOT NULL,
    history TEXT,
    vision_mission TEXT,
    address TEXT,
    phone TEXT,
    email TEXT,
    operational_hours TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS education_units (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    description TEXT,
    curriculum TEXT,
    extracurricular TEXT,
    facilities TEXT,
    wa_number TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS facilities (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    description TEXT,
    image_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ppdb_info (
    id INT PRIMARY KEY DEFAULT 1,
    academic_year TEXT NOT NULL,
    status TEXT DEFAULT 'TUTUP',
    schedule TEXT,
    requirements TEXT,
    flow TEXT,
    fees TEXT,
    wa_number TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS news_posts (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    content TEXT,
    date DATE DEFAULT CURRENT_DATE,
    image_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS galleries (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title TEXT NOT NULL,
    image_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

