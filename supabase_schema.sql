    id INT PRIMARY KEY DEFAULT 1,
    foundation_name TEXT DEFAULT 'Yayasan Nahjul Huda',
    address TEXT,
    phone TEXT,
    whatsapp1 TEXT,
    whatsapp2 TEXT,
    email TEXT,
    operational_hours TEXT,
    maps_embed_url TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
