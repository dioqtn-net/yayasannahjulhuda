export async function renderDynamicUnitModal(id) {
  let numId = Number(id);
  let key = 'sdi';
  if (numId >= 1 && numId <= 5) {
    key = unitModalMetadata[numId].key;
  } else if (typeof id === 'string') {
    const found = Object.entries(unitModalMetadata).find(([k, v]) => v.key === id.toLowerCase());
    if (found) {
      numId = Number(found[0]);
      key = found[1].key;
    }
  }

  const meta = unitModalMetadata[numId] || unitModalMetadata[1];
  const defaults = defaultUnitProgramData[key] || defaultUnitProgramData.sdi;

  // 1. Fetch from localStorage CMS Program
  let cmsProg = {};
  try {
    const raw = typeof localStorage !== 'undefined' ? localStorage.getItem('cmsData_program') : null;
    if (raw) cmsProg = JSON.parse(raw);
  } catch(e) {}

  // 2. Fetch from localStorage CMS PPDB
  let cmsPPDB = {};
  try {
    const raw = typeof localStorage !== 'undefined' ? localStorage.getItem('cmsData_ppdb') : null;
    if (raw) cmsPPDB = JSON.parse(raw);
  } catch(e) {}

  // 3. Fetch from localStorage CMS Contact
  let cmsContact = {};
  try {
    const raw = typeof localStorage !== 'undefined' ? localStorage.getItem('cmsData_contact') : null;
    if (raw) cmsContact = JSON.parse(raw);
  } catch(e) {}

  // 4. Supabase fetch if client available
  if (typeof window !== 'undefined' && window.supabaseClient) {
    try {
      const { data: supaUnits } = await window.supabaseClient.from('education_units').select('*');
      if (supaUnits && supaUnits.length > 0) {
        const matching = supaUnits.find(u => u.id === numId || (u.name && u.name.toLowerCase().includes(key)));
        if (matching) {
          if (matching.description) cmsProg[key + 'Desc'] = cmsProg[key + 'Desc'] || matching.description;
          if (matching.curriculum) cmsProg[key + 'Kurikulum'] = cmsProg[key + 'Kurikulum'] || matching.curriculum;
          if (matching.extracurricular) cmsProg[key + 'Ekskul'] = cmsProg[key + 'Ekskul'] || matching.extracurricular;
          if (matching.facilities) cmsProg[key + 'Fasilitas'] = cmsProg[key + 'Fasilitas'] || matching.facilities;
          if (matching.featured_program) cmsProg[key + 'Unggulan'] = cmsProg[key + 'Unggulan'] || matching.featured_program;
        }
      }
    } catch(err) {
      // offline / fallback
    }
  }

  const desc = cmsProg[key + 'Desc'] || defaults.desc;
  const kurikulum = cmsProg[key + 'Kurikulum'] || defaults.kurikulum;
  const unggulan = cmsProg[key + 'Unggulan'] || defaults.unggulan;
  const ekskul = cmsProg[key + 'Ekskul'] || defaults.ekskul;
  const fasilitas = cmsProg[key + 'Fasilitas'] || defaults.fasilitas;
  const visi = cmsProg[key + 'Visi'] || defaults.visi;
  const misi = cmsProg[key + 'Misi'] || defaults.misi;
  let akreditasi = cmsProg[key + 'Akreditasi'] || defaults.akreditasi;
  if (akreditasi && !akreditasi.toLowerCase().startsWith('akreditasi') && akreditasi !== '-') {
    akreditasi = 'Akreditasi ' + akreditasi;
  }

  // Update title & akreditasi badge if elements exist
  const elTitle = document.getElementById(`modal-title-${numId}`);
  if (elTitle) elTitle.textContent = meta.name;
  const elAkreditasi = document.getElementById(`modal-akreditasi-${numId}`);
  if (elAkreditasi) elAkreditasi.textContent = akreditasi;

  const modalBody = document.getElementById(`modal-body-${numId}`) || 
                    (document.getElementById(`modal-${numId}`) ? document.getElementById(`modal-${numId}`).querySelector('.overflow-y-auto') : null);

  if (modalBody) {
    const escapeHtml = (str) => {
      if (!str) return '';
      const div = document.createElement('div');
      div.textContent = str;
      return div.innerHTML;
    };

    const linesMisi = (misi || '')
      .split('\n')
      .map(l => l.trim().replace(/^[-*•\d.]+\s*/, ''))
      .filter(l => l.length > 0 && l !== '-');

    const misiHTML = linesMisi.length > 0
      ? `<ol class="list-decimal ml-5 space-y-1.5 text-sm text-slate-600 leading-relaxed">${linesMisi.map(m => `<li>${escapeHtml(m)}</li>`).join('')}</ol>`
      : '<p class="text-sm text-slate-500 italic">-</p>';

    const makeWALink = (phone, name) => {
      if (!phone) return '#';
      let clean = phone.replace(/\D/g, '');
      if (clean.startsWith('0')) clean = '62' + clean.slice(1);
      else if (clean.startsWith('8')) clean = '62' + clean;
      const msg = `Halo ${name || 'Admin'}, saya ingin bertanya seputar ${meta.name}.`;
      return `https://wa.me/${clean}?text=${encodeURIComponent(msg)}`;
    };

    const ppdbUnit = (cmsPPDB && cmsPPDB[key]) ? cmsPPDB[key] : {};
    const k1 = ppdbUnit.kontak1_nama && ppdbUnit.kontak1_wa ? { nama: ppdbUnit.kontak1_nama, wa: ppdbUnit.kontak1_wa } : null;
    const k2 = ppdbUnit.kontak2_nama && ppdbUnit.kontak2_wa ? { nama: ppdbUnit.kontak2_nama, wa: ppdbUnit.kontak2_wa } : null;

    let contactItemsHTML = '';
    if (k1) {
      contactItemsHTML += `
        <a href="${makeWALink(k1.wa, k1.nama)}" target="_blank" class="inline-flex items-center gap-1.5 px-3 py-1.5 bg-emerald-50 hover:bg-emerald-100 text-emerald-800 rounded-lg text-xs font-semibold border border-emerald-200 transition shadow-xs">
          <i class="fab fa-whatsapp text-emerald-600 text-sm"></i>
          <span>${escapeHtml(k1.nama)} (${escapeHtml(k1.wa)})</span>
        </a>
      `;
    }
    if (k2) {
      contactItemsHTML += `
        <a href="${makeWALink(k2.wa, k2.nama)}" target="_blank" class="inline-flex items-center gap-1.5 px-3 py-1.5 bg-emerald-50 hover:bg-emerald-100 text-emerald-800 rounded-lg text-xs font-semibold border border-emerald-200 transition shadow-xs">
          <i class="fab fa-whatsapp text-emerald-600 text-sm"></i>
          <span>${escapeHtml(k2.nama)} (${escapeHtml(k2.wa)})</span>
        </a>
      `;
    }
    if (defaults.email) {
      contactItemsHTML += `
        <a href="mailto:${defaults.email}" class="inline-flex items-center gap-1.5 px-3 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold border border-slate-200 transition shadow-xs">
          <i class="fas fa-envelope text-slate-500"></i>
          <span>${defaults.email}</span>
        </a>
      `;
    }
    if (defaults.telp) {
      contactItemsHTML += `
        <a href="tel:${defaults.telp.replace(/\D/g, '')}" class="inline-flex items-center gap-1.5 px-3 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold border border-slate-200 transition shadow-xs">
          <i class="fas fa-phone-alt text-slate-500"></i>
          <span>${defaults.telp}</span>
        </a>
      `;
    }
    if (!contactItemsHTML) {
      const genWA = cmsContact.wa1 || '081234567890';
      contactItemsHTML = `
        <a href="${makeWALink(genWA, 'Layanan Yayasan')}" target="_blank" class="inline-flex items-center gap-1.5 px-3 py-1.5 bg-emerald-50 hover:bg-emerald-100 text-emerald-800 rounded-lg text-xs font-semibold border border-emerald-200 transition shadow-xs">
          <i class="fab fa-whatsapp text-emerald-600 text-sm"></i>
          <span>Layanan Yayasan (${escapeHtml(genWA)})</span>
        </a>
      `;
    }

    modalBody.innerHTML = `
      <div class="w-full h-48 sm:h-64 mb-6 rounded-xl bg-white border border-slate-100 flex items-center justify-center p-4 shadow-sm">
        <img src="${meta.logo}" alt="${escapeHtml(meta.name)}" class="object-contain max-h-full w-auto">
      </div>

      <p class="text-slate-700 mb-6 leading-relaxed">${escapeHtml(desc)}</p>

      <div class="mb-4">
        <h4 class="font-bold text-emerald-700 mb-1.5 flex items-center"><i class="fas fa-book-reader mr-2 text-gold-500"></i> Kurikulum</h4>
        <p class="text-slate-600 text-sm leading-relaxed">${escapeHtml(kurikulum)}</p>
      </div>

      ${unggulan && unggulan !== '-' ? `
      <div class="mb-4">
        <h4 class="font-bold text-emerald-700 mb-1.5 flex items-center"><i class="fas fa-star mr-2 text-gold-500"></i> Program Unggulan</h4>
        <p class="text-slate-600 text-sm leading-relaxed">${escapeHtml(unggulan)}</p>
      </div>
      ` : ''}

      <div class="mb-4">
        <h4 class="font-bold text-emerald-700 mb-1.5 flex items-center"><i class="fas fa-running mr-2 text-gold-500"></i> Ekstrakurikuler</h4>
        <p class="text-slate-600 text-sm leading-relaxed">${escapeHtml(ekskul)}</p>
      </div>

      <div class="mb-4">
        <h4 class="font-bold text-emerald-700 mb-1.5 flex items-center"><i class="fas fa-building mr-2 text-gold-500"></i> Fasilitas</h4>
        <p class="text-slate-600 text-sm leading-relaxed">${escapeHtml(fasilitas)}</p>
      </div>

      <div class="mb-4 p-4 sm:p-5 bg-slate-50 rounded-xl border border-slate-200/80">
        <h4 class="font-bold text-emerald-800 mb-2 flex items-center"><i class="fas fa-bullseye mr-2 text-gold-500"></i> Visi &amp; Misi</h4>
        <div class="mb-3">
          <span class="font-semibold text-emerald-800 text-xs uppercase tracking-wider block mb-1">Visi:</span>
          <p class="italic text-slate-700 text-sm leading-relaxed">${escapeHtml(visi)}</p>
        </div>
        <div>
          <span class="font-semibold text-emerald-800 text-xs uppercase tracking-wider block mb-1">Misi:</span>
          ${misiHTML}
        </div>
      </div>

      <!-- Kontak Layanan PPDB / Sekolah -->
      <div class="mt-5 p-4 bg-slate-50 border border-slate-200/80 rounded-xl space-y-2.5">
        <div class="flex items-center justify-between">
          <h4 class="font-bold text-emerald-800 text-xs uppercase tracking-wider flex items-center">
            <i class="fas fa-id-card text-gold-500 mr-2 text-sm"></i> Kontak &amp; Layanan PPDB ${meta.short}:
          </h4>
          <span class="text-[10px] font-bold text-emerald-800 bg-emerald-100/70 px-2 py-0.5 rounded">Aktif</span>
        </div>
        <div class="flex flex-wrap items-center gap-2 pt-1">
          ${contactItemsHTML}
        </div>
      </div>
    `;
  }
}
